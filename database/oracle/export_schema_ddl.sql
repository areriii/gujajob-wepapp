-- ดึง DDL ของทุกตาราง/อินเด็กซ์/คอนสเตรนต์ในสคีมาปัจจุบันออกเป็นไฟล์เดียว
-- วิธีใช้:  sqlplus -S asset/<password>@localhost:1521/orclpdb @export_schema_ddl.sql
-- ผลลัพธ์:  database/oracle/schema_full.sql  (เอาเข้า git เพื่อให้สร้าง DB ใหม่ได้ทุกเครื่อง)

set heading off feedback off verify off trimspool on pagesize 0
set linesize 32767 long 2000000 longchunksize 2000000
set define off

begin
  dbms_metadata.set_transform_param(dbms_metadata.session_transform,'SQLTERMINATOR',true);
  dbms_metadata.set_transform_param(dbms_metadata.session_transform,'PRETTY',true);
  dbms_metadata.set_transform_param(dbms_metadata.session_transform,'SEGMENT_ATTRIBUTES',false);
  dbms_metadata.set_transform_param(dbms_metadata.session_transform,'STORAGE',false);
  dbms_metadata.set_transform_param(dbms_metadata.session_transform,'TABLESPACE',false);
end;
/

spool database/oracle/schema_full.sql

prompt -- =============================================================
prompt -- GUJAJOB schema - generated by export_schema_ddl.sql
prompt -- สร้างใหม่ด้วย: sqlplus asset/<pw>@host:1521/orclpdb @schema_full.sql
prompt -- =============================================================

-- ตาราง
select dbms_metadata.get_ddl('TABLE', table_name) from user_tables order by table_name;

-- ซีเควนซ์
select dbms_metadata.get_ddl('SEQUENCE', sequence_name) from user_sequences order by sequence_name;

-- อินเด็กซ์ (ข้ามตัวที่ระบบสร้างให้ constraint)
select dbms_metadata.get_ddl('INDEX', index_name)
from   user_indexes
where  generated = 'N' and index_type <> 'LOB'
order  by index_name;

-- วิว
select dbms_metadata.get_ddl('VIEW', view_name) from user_views order by view_name;

-- ทริกเกอร์
select dbms_metadata.get_ddl('TRIGGER', trigger_name) from user_triggers order by trigger_name;

spool off
exit
