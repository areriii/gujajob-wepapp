FROM ASSET a
LEFT JOIN ASSET_ASSIGNMENT_LIST aal ON aal.ASSET_ID = a.ID
LEFT JOIN ASSET_ASSIGNMENT aa ON aa.ID = aal.ASS_ASSIGN_ID AND aa.REMARK LIKE '[ALLOCATION DEMO DATA]%'
WHERE a.REMARKS LIKE '[ALLOCATION DEMO DATA]%'
ORDER BY a.ASS_CODE;

